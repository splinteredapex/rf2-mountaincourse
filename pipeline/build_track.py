"""Generate track geometry for one section of the course.

    python pipeline/build_track.py pilot

Reads the traced centreline and the elevation model, and writes to build/<section>/:
    track.obj / track.mtl   every mesh object, named as rFactor 2 expects
    centreline.csv          station, local x/y/z, heading: the reference for all later placement
    preview.png             plan view and height profile

Design rule: every vertex is positioned by (station along the road, offset sideways).
Better height data (GPS laps, LiDAR) replaces `road_profile()` and `ground_height()`;
everything else follows the road automatically.

Local axes in this script: x = east, y = north, z = up, metres.
The OBJ is written Y-up / -Z-forward, which is Blender's default OBJ import setting.
"""
from __future__ import annotations
import csv, math, sys
from pathlib import Path
import numpy as np
import rasterio
import yaml
from pyproj import Transformer
from scipy.interpolate import splev, splprep
from scipy.ndimage import gaussian_filter, gaussian_filter1d, map_coordinates
from scipy.spatial import cKDTree

ROOT = Path(__file__).resolve().parents[1]
TO_LONLAT = Transformer.from_crs("EPSG:27700", "EPSG:4326", always_xy=True)


# ----------------------------------------------------------------------------- data
class Dem:
    """Open elevation model, lightly smoothed. Swap this class out for LiDAR later."""

    def __init__(self, path: Path, smooth_px: float):
        with rasterio.open(path) as src:
            self.z = gaussian_filter(src.read(1).astype("float64"), smooth_px)
            self.inv = ~src.transform

    def at(self, e: np.ndarray, n: np.ndarray) -> np.ndarray:
        lon, lat = TO_LONLAT.transform(e, n)
        lon, lat, t = np.asarray(lon), np.asarray(lat), self.inv
        col, row = t.a * lon + t.b * lat + t.c, t.d * lon + t.e * lat + t.f
        return map_coordinates(self.z, [row - 0.5, col - 0.5], order=1, mode="nearest")


def load_centreline(path: Path):
    rows = list(csv.DictReader(path.open()))
    s = np.array([float(r["station_m"]) for r in rows])
    e = np.array([float(r["easting"]) for r in rows])
    n = np.array([float(r["northing"]) for r in rows])
    keep = np.r_[True, np.diff(s) > 0.01]
    return s[keep], e[keep], n[keep]


def resample(s, e, n, s0, s1, step, tolerance):
    """Smooth spline through the map polyline, resampled every `step` metres."""
    pad = 150.0
    m = (s >= s0 - pad) & (s <= s1 + pad)
    ss, ee, nn = s[m], e[m], n[m]
    tck, _ = splprep([ee, nn], u=ss, s=len(ss) * tolerance**2, k=3)
    # Re-measure true arc length along the spline so stations stay honest.
    fine = np.arange(ss[0], ss[-1], 0.25)
    fe, fn = splev(fine, tck)
    arc = np.r_[0.0, np.cumsum(np.hypot(np.diff(fe), np.diff(fn)))] + ss[0]
    target = np.arange(s0, s1 + step * 0.5, step)
    u = np.interp(target, arc, fine)
    pe, pn = splev(u, tck)
    de, dn = splev(u, tck, der=1)
    norm = np.hypot(de, dn)
    return target, np.asarray(pe), np.asarray(pn), de / norm, dn / norm


# ----------------------------------------------------------------------------- mesh helpers
class Obj:
    def __init__(self):
        self.objects: list[tuple[str, str, np.ndarray, np.ndarray, np.ndarray]] = []

    def add(self, name, material, verts, uvs, faces):
        """verts (N,3) local x/y/z; uvs (N,2); faces (M,4) or (M,3) zero-based."""
        used = np.unique(faces)
        remap = -np.ones(len(verts), dtype=int)
        remap[used] = np.arange(len(used))
        self.objects.append((name, material, verts[used], uvs[used], remap[faces]))

    def write(self, path: Path, materials: dict):
        mtl = path.with_suffix(".mtl")
        with mtl.open("w") as f:
            for name, rgb in materials.items():
                f.write(f"newmtl {name}\nKd {rgb[0]} {rgb[1]} {rgb[2]}\n\n")
        base = 1
        with path.open("w") as f:
            f.write(f"# generated by pipeline/build_track.py - do not edit by hand\nmtllib {mtl.name}\n")
            for name, material, v, uv, faces in self.objects:
                f.write(f"o {name}\n")
                for x, y, z in v:  # local (east, north, up) -> OBJ (x, up, -north)
                    f.write(f"v {x:.4f} {z:.4f} {-y:.4f}\n")
                for a, b in uv:
                    f.write(f"vt {a:.4f} {b:.4f}\n")
                f.write(f"usemtl {material}\ns 1\n")
                for face in faces:
                    f.write("f " + " ".join(f"{i + base}/{i + base}" for i in face) + "\n")
                base += len(v)
        return sum(len(o[4]) for o in self.objects)


def grid_faces(rows: range, cols: range, ncols: int) -> np.ndarray:
    """Quads for a (station, offset) grid. Offsets increase to the left, so faces point up."""
    i, j = np.meshgrid(np.array(rows), np.array(cols), indexing="ij")
    a = (i * ncols + j).ravel()
    return np.stack([a, a + ncols, a + ncols + 1, a + 1], axis=1)


def smoothstep(t):
    t = np.clip(t, 0.0, 1.0)
    return t * t * (3 - 2 * t)


# ----------------------------------------------------------------------------- build
def build(section_name: str):
    cfg = yaml.safe_load((ROOT / "config/course.yaml").read_text())
    sec = cfg["sections"][section_name]
    road, rib, far = cfg["road"], cfg["corridor"], cfg["far_terrain"]
    out = ROOT / "build" / section_name
    out.mkdir(parents=True, exist_ok=True)

    s_all, e_all, n_all = load_centreline(ROOT / "data/course_centreline.csv")
    s0, s1 = sec["start_km"] * 1000.0, sec["end_km"] * 1000.0
    st, pe, pn, te, tn = resample(s_all, e_all, n_all, s0, s1, road["station_step_m"], road["centreline_tolerance_m"])
    nst = len(st)
    le, ln = -tn, te  # unit vector pointing left of travel

    dem = Dem(ROOT / cfg["data"]["dem"], cfg["elevation"]["dem_smooth_px"])

    # Road height profile: the only place the road's undulation comes from.
    def road_profile():
        z = dem.at(pe, pn)
        return gaussian_filter1d(z, cfg["elevation"]["profile_smooth_m"] / road["station_step_m"], mode="nearest")

    def ground_height(e, n):
        return dem.at(e, n)

    zc = road_profile()

    # Logged drives, if any: replace the open-data road profile where drives cover it.
    delta = np.zeros(nst)
    drive_cover = 0.0
    prof_path = ROOT / "data/road_profile.csv"
    if cfg["elevation"].get("use_drive_profile", True) and prof_path.exists():
        delta, drive_cover = drive_delta(prof_path, st, zc, cfg["elevation"])
        zc = zc + delta

    # Curvature check: the corridor ribbon folds over itself inside bends tighter than its width.
    heading = np.unwrap(np.arctan2(tn, te))
    curv = np.abs(np.gradient(heading, st))
    min_radius = 1.0 / max(curv.max(), 1e-9)

    # Local origin: middle of the section, so coordinates stay small (float precision).
    e0, n0, z0 = float(pe.mean()), float(pn.mean()), float(zc.mean())

    # ---- cross-section offsets, far right (-) to far left (+)
    half = road["width_m"] / 2.0
    road_off = np.linspace(-half, half, road["lateral_quads"] + 1)
    side = np.array(rib["offsets_m"], dtype=float)  # distances beyond the road edge
    offs = np.r_[-(half + side[::-1]), road_off, half + side]
    ncols = len(offs)
    c_road0 = len(side)                    # first road column
    c_road1 = c_road0 + len(road_off) - 1  # last road column

    # ---- pit lane: a flat strip on the left, used so the game has a pit to spawn in
    pit = sec.get("pit")
    pit_shift = np.zeros(nst)
    if pit:
        ps, pl, tp = s0 + pit["start_m"], pit["length_m"], pit["taper_m"]
        rel = st - ps
        pit_shift = pit["width_m"] * np.clip(np.minimum(rel / tp, (pl - rel) / tp), 0.0, 1.0)

    # ---- heights
    off2 = np.broadcast_to(offs, (nst, ncols))
    E = pe[:, None] + le[:, None] * off2
    N = pn[:, None] + ln[:, None] * off2
    crown = -road["crossfall"] * np.abs(off2)           # falls away from the centre line
    plane = zc[:, None] + crown                          # road surface extended sideways
    beyond = np.abs(off2) - half
    shift = np.where(off2 > 0, pit_shift[:, None], 0.0)  # pit strip stays on the road plane
    w = smoothstep((beyond - shift) / rib["blend_m"])
    w = np.where(beyond <= 0, 0.0, w)
    ground = ground_height(E.ravel(), N.ravel()).reshape(nst, ncols)
    # Carry the drive correction into the ground beside the road, fading out across the corridor.
    ground = ground + delta[:, None] * (1 - smoothstep(beyond / side[-1]))
    Z = plane * (1 - w) + (ground - rib["verge_drop_m"] * np.minimum(w * 4, 1.0)) * w
    Z = np.where(beyond <= 0, plane, Z)

    V = np.stack([E - e0, N - n0, Z - z0], axis=2).reshape(-1, 3)
    UV = np.stack([(off2 - offs[0]) / road["uv_tile_m"], np.broadcast_to(st[:, None], (nst, ncols)) / road["uv_tile_m"]],
                  axis=2).reshape(-1, 2)

    obj = Obj()
    chunk = int(round(road["chunk_m"] / road["station_step_m"]))
    pit_cols = 0
    if pit:
        pit_cols = int(np.searchsorted(side, pit["width_m"] + 1e-6))  # ribbon columns the strip covers
    for k, r0 in enumerate(range(0, nst - 1, chunk)):
        rows = range(r0, min(r0 + chunk, nst - 1))
        obj.add(f"RaceSurface_{k + 1:03d}", "road_asphalt", V, UV, grid_faces(rows, range(c_road0, c_road1), ncols))
        obj.add(f"VergeR_{k + 1:03d}", "grass_verge", V, UV, grid_faces(rows, range(0, c_road0), ncols))
        left = grid_faces(rows, range(c_road1, ncols - 1), ncols)
        if pit:
            col = (left[:, 0] % ncols) - c_road1
            row = left[:, 0] // ncols
            in_pit = (col < pit_cols) & (pit_shift[row] > 0) & (pit_shift[np.minimum(row + 1, nst - 1)] > 0)
            if in_pit.any():
                obj.add(f"PitLane_{k + 1:03d}", "road_pitlane", V, UV, left[in_pit])
            left = left[~in_pit]
        obj.add(f"VergeL_{k + 1:03d}", "grass_verge", V, UV, left)

    # ---- far terrain: plain grid from the elevation model, with the road corridor cut out
    g = far["grid_m"]
    xs = np.arange(pe.min() - far["margin_m"], pe.max() + far["margin_m"] + g, g)
    ys = np.arange(pn.min() - far["margin_m"], pn.max() + far["margin_m"] + g, g)
    GX, GY = np.meshgrid(xs, ys, indexing="ij")
    GZ = ground_height(GX.ravel(), GY.ravel())
    d, _ = cKDTree(np.c_[pe, pn]).query(np.c_[GX.ravel(), GY.ravel()])
    edge = half + side[-1]
    GZ = GZ - far["sink_m"] * (1 - smoothstep((d - edge) / (2 * g)))  # tuck under the corridor edge
    gv = np.c_[GX.ravel() - e0, GY.ravel() - n0, GZ - z0]
    guv = np.c_[GX.ravel(), GY.ravel()] / far["uv_tile_m"]
    ny = len(ys)
    gi, gj = np.meshgrid(np.arange(len(xs) - 1), np.arange(ny - 1), indexing="ij")
    a = (gi * ny + gj).ravel()
    gf = np.stack([a, a + ny, a + ny + 1, a + 1], axis=1)
    keep = (d[gf] > edge - g * 0.25).any(axis=1)  # drop cells wholly inside the corridor
    obj.add("Terrain_Far", "grass_terrain", gv, guv, gf[keep])

    # ---- timing gates: vertical planes across the road, named as the game requires
    def gate(name, station_m, c0, c1, material="gate"):
        i = int(np.clip(round((station_m - s0) / road["station_step_m"]), 1, nst - 2))
        a, b = V[i * ncols + c0], V[i * ncols + c1]
        up = np.array([0, 0, 5.0])
        obj.add(name, material, np.array([a, b, b + up, a + up]), np.array([[0, 0], [1, 0], [1, 1], [0, 1]]),
                np.array([[0, 1, 2, 3]]))

    length = s1 - s0
    gate("xfinish", s0 + sec["finish_m"], c_road0, c_road1)
    gate("xsector1", s0 + length / 3, c_road0, c_road1)
    gate("xsector2", s0 + 2 * length / 3, c_road0, c_road1)
    if pit:
        gate("xpitin", s0 + pit["start_m"] + pit["taper_m"], c_road1, c_road1 + pit_cols)
        gate("xpitout", s0 + pit["start_m"] + pit["length_m"] - pit["taper_m"], c_road1, c_road1 + pit_cols)

    nfaces = obj.write(out / "track.obj", cfg["materials"])

    with (out / "centreline.csv").open("w", newline="") as f:
        wr = csv.writer(f)
        wr.writerow(["station_m", "x_east", "y_north", "z_up", "heading_deg", "height_asl_m"])
        for i in range(nst):
            wr.writerow([f"{st[i]:.1f}", f"{pe[i] - e0:.3f}", f"{pn[i] - n0:.3f}", f"{zc[i] - z0:.3f}",
                         f"{math.degrees(heading[i]) % 360:.2f}", f"{zc[i]:.2f}"])

    lon0, lat0 = TO_LONLAT.transform(e0, n0)
    info = {
        "section": section_name, "length_m": round(float(length), 1), "stations": nst, "faces": int(nfaces),
        "origin_lat": round(lat0, 6), "origin_lon": round(lon0, 6), "origin_height_asl_m": round(z0, 2),
        "height_min_asl_m": round(float(zc.min()), 1), "height_max_asl_m": round(float(zc.max()), 1),
        "tightest_radius_m": round(float(min_radius), 1), "corridor_half_width_m": round(float(edge), 1),
        "corridor_folds": bool(min_radius < edge),
        "height_source": "logged drives" if drive_cover > 0 else "open 30 m data",
        "drive_coverage_pct": round(100 * drive_cover, 1),
    }
    (out / "build_info.yaml").write_text(yaml.safe_dump(info, sort_keys=False))
    preview(out / "preview.png", st - s0, pe - e0, pn - n0, zc, section_name)
    for k, v in info.items():
        print(f"  {k}: {v}")
    if info["corridor_folds"]:
        print("  WARNING: a bend is tighter than the corridor width; the verge mesh overlaps itself there.")
    return info


def drive_delta(path: Path, st: np.ndarray, z_open: np.ndarray, ecfg: dict):
    """Correction to add to the open-data profile, from data/road_profile.csv (see fuse_drives.py).

    Where drives do not reach, the correction fades to zero so the road rejoins the open-data profile.
    """
    rows = list(csv.DictReader(path.open()))
    ps = np.array([float(r["station_m"]) for r in rows])
    ph = np.array([float(r["height_m"]) for r in rows])
    pn = np.array([int(r["n_passes"]) for r in rows])
    keep = pn >= ecfg.get("min_passes", 1)
    ps, ph = ps[keep], ph[keep]
    if len(ps) < 2:
        return np.zeros(len(st)), 0.0
    step = float(np.median(np.diff(ps)))
    i = np.searchsorted(ps, st).clip(1, len(ps) - 1)
    near = np.where(np.abs(st - ps[i - 1]) <= np.abs(ps[i] - st), i - 1, i)
    dist = np.abs(st - ps[near])                       # distance to the nearest covered station
    covered = (dist <= step) & (ps[i] - ps[i - 1] <= 2.5 * step) | (dist < 1e-6)
    d = np.interp(st, ps, ph) - z_open
    d_near = ph[near] - np.interp(ps[near], st, z_open)
    fade = 1 - smoothstep(dist / ecfg.get("drive_fade_m", 200.0))
    return np.where(covered, d, d_near * fade), float(covered.mean())


def preview(path, s, x, y, z, title):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, (a, b) = plt.subplots(2, 1, figsize=(10, 8), height_ratios=[2, 1])
    a.plot(x, y, color="#333", lw=2)
    a.scatter([x[0]], [y[0]], color="green", zorder=3, label="start")
    a.scatter([x[-1]], [y[-1]], color="red", zorder=3, label="end")
    a.set_aspect("equal"); a.set_title(f"{title}: plan view (metres, north up)"); a.legend(); a.grid(alpha=.3)
    b.plot(s, z, color="#1f77b4"); b.set_xlabel("distance along section (m)"); b.set_ylabel("height above sea level (m)")
    b.set_title("road height profile"); b.grid(alpha=.3)
    fig.tight_layout(); fig.savefig(path, dpi=110); plt.close(fig)


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else "pilot")
